//! PDFium-backed implementation of [`crate::PdfEngine`].
//!
//! Port target: `liteparse/src/engines/pdf/pdfjs.ts` (text extraction) +
//! `pdfium-renderer.ts` (rasterization). We unify both under PDFium so the
//! Rust build has a single native dependency.
//!
//! ## Library discovery
//!
//! We try, in order:
//! 1. `Pdfium::bind_to_library(path)` where `path` is `$PDFIUM_LIB_PATH` (an
//!    explicit file path).
//! 2. A copy of `libpdfium` that was embedded at build time (via the
//!    `bundled-pdfium` feature) and extracted to the user cache dir on first
//!    run. This is the default path for end-user installs.
//! 3. `Pdfium::bind_to_library(path)` with a path inferred from the `xtask
//!    pdfium-download` layout — `./pdfium/<triple>/lib/libpdfium.{dylib,so}`
//!    or `./pdfium/<triple>/bin/pdfium.dll`.
//! 4. `Pdfium::bind_to_system_library()` for system-wide installs.
//!
//! ## Threading
//!
//! `pdfium-render`'s bindings are not thread-safe by default; the
//! `thread_safe` feature adds an internal mutex. We still serialise calls
//! through the engine to be defensive against library misuse.

use std::path::{Path, PathBuf};
use std::sync::{Mutex, OnceLock};

use pdfium_render::prelude::{PdfPageObjectsCommon, PdfRenderConfig, Pdfium};
use spdf_types::{Image, SpdfError, SpdfResult, TextItem};
use tracing::{debug, warn};

use crate::engine::{ExtractOptions, PageData, PdfDocumentHandle, PdfEngine};

// Generated by `build.rs`. Provides:
//   pub const BYTES: &[u8]      — embedded libpdfium for the host target, or
//                                 an empty slice when bundling is disabled.
//   pub const LIB_NAME: &str    — platform filename (e.g. "libpdfium.so").
mod pdfium_bundle {
    include!(concat!(env!("OUT_DIR"), "/pdfium_bundle.rs"));
}

fn candidate_library_paths() -> Vec<PathBuf> {
    let mut out = Vec::new();
    if let Ok(explicit) = std::env::var("PDFIUM_LIB_PATH") {
        out.push(PathBuf::from(explicit));
    }
    // Embedded library, extracted once to a user cache dir.
    if let Some(p) = extract_bundled_library() {
        out.push(p);
    }
    let triple = current_triple();
    let (subdir, name) = if cfg!(target_os = "windows") {
        ("bin", "pdfium.dll")
    } else if cfg!(target_os = "macos") {
        ("lib", "libpdfium.dylib")
    } else {
        ("lib", "libpdfium.so")
    };
    for root in ["pdfium", "../pdfium", "../../pdfium"] {
        out.push(PathBuf::from(root).join(triple).join(subdir).join(name));
    }
    out
}

/// If a libpdfium was embedded at build time, write it to a stable cache
/// directory (keyed by crate version) and return the path. Returns `None`
/// when bundling was disabled or the write fails — callers fall back to the
/// other discovery mechanisms.
fn extract_bundled_library() -> Option<PathBuf> {
    if pdfium_bundle::BYTES.is_empty() || pdfium_bundle::LIB_NAME.is_empty() {
        return None;
    }
    let cache_root = user_cache_dir()?;
    let dir = cache_root
        .join("spdf")
        .join(concat!("pdfium-v", env!("CARGO_PKG_VERSION")));
    let lib_path = dir.join(pdfium_bundle::LIB_NAME);
    if lib_path.is_file() {
        return Some(lib_path);
    }
    if let Err(e) = std::fs::create_dir_all(&dir) {
        warn!(path = %dir.display(), error = %e, "pdfium: cache mkdir failed");
        return None;
    }
    // Write atomically: write to a temp file, then rename.
    let tmp = dir.join(format!("{}.partial", pdfium_bundle::LIB_NAME));
    if let Err(e) = std::fs::write(&tmp, pdfium_bundle::BYTES) {
        warn!(path = %tmp.display(), error = %e, "pdfium: cache write failed");
        return None;
    }
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        let _ = std::fs::set_permissions(&tmp, std::fs::Permissions::from_mode(0o755));
    }
    if let Err(e) = std::fs::rename(&tmp, &lib_path) {
        warn!(path = %lib_path.display(), error = %e, "pdfium: cache rename failed");
        return None;
    }
    debug!(path = %lib_path.display(), bytes = pdfium_bundle::BYTES.len(), "pdfium: extracted bundled library");
    Some(lib_path)
}

fn user_cache_dir() -> Option<PathBuf> {
    #[cfg(target_os = "windows")]
    {
        if let Some(p) = std::env::var_os("LOCALAPPDATA") {
            return Some(PathBuf::from(p));
        }
    }
    #[cfg(target_os = "macos")]
    {
        if let Some(home) = std::env::var_os("HOME") {
            return Some(PathBuf::from(home).join("Library").join("Caches"));
        }
    }
    #[cfg(all(unix, not(target_os = "macos")))]
    {
        if let Some(xdg) = std::env::var_os("XDG_CACHE_HOME") {
            return Some(PathBuf::from(xdg));
        }
        if let Some(home) = std::env::var_os("HOME") {
            return Some(PathBuf::from(home).join(".cache"));
        }
    }
    // Last-resort fallback: OS temp dir (survives for the session at least).
    Some(std::env::temp_dir())
}

fn current_triple() -> &'static str {
    match (std::env::consts::OS, std::env::consts::ARCH) {
        ("macos", "aarch64") => "aarch64-apple-darwin",
        ("macos", "x86_64") => "x86_64-apple-darwin",
        ("linux", "x86_64") => "x86_64-unknown-linux-gnu",
        ("linux", "aarch64") => "aarch64-unknown-linux-gnu",
        ("windows", "x86_64") => "x86_64-pc-windows-msvc",
        _ => "unknown",
    }
}

/// Global PDFium library handle. PDFium's C API keeps internal global state;
/// a single process-wide instance is the safest usage.
fn pdfium() -> SpdfResult<&'static Mutex<Pdfium>> {
    static LIB: OnceLock<Result<Mutex<Pdfium>, String>> = OnceLock::new();
    let entry = LIB.get_or_init(|| {
        for candidate in candidate_library_paths() {
            if candidate.is_file() {
                let path_str = candidate.to_string_lossy().into_owned();
                match Pdfium::bind_to_library(&path_str) {
                    Ok(b) => {
                        debug!(path = %path_str, "pdfium: bound to explicit library");
                        return Ok(Mutex::new(Pdfium::new(b)));
                    }
                    Err(e) => warn!(path = %path_str, error = %e, "pdfium: explicit bind failed"),
                }
            }
        }
        match Pdfium::bind_to_system_library() {
            Ok(b) => {
                debug!("pdfium: bound to system library");
                Ok(Mutex::new(Pdfium::new(b)))
            }
            Err(e) => Err(format!(
                "no pdfium library found. The default build embeds pdfium; if you \
                 disabled `bundled-pdfium` you must provide one via PDFIUM_LIB_PATH, \
                 `cargo run -p xtask -- pdfium-download`, or a system install. last error: {e}"
            )),
        }
    });
    entry
        .as_ref()
        .map_err(|e| SpdfError::Pdf(format!("pdfium unavailable: {e}")))
}

#[derive(Debug)]
pub struct PdfiumDoc {
    /// We keep the PDF bytes alive for the lifetime of the handle because
    /// `PdfDocument` borrows them internally. Simpler than juggling lifetimes
    /// in a trait object.
    bytes: Vec<u8>,
    num_pages: u32,
    password: Option<String>,
}

impl PdfDocumentHandle for PdfiumDoc {
    fn num_pages(&self) -> u32 {
        self.num_pages
    }
}

#[derive(Debug, Default)]
pub struct PdfiumEngine;

impl PdfiumEngine {
    pub fn new() -> Self {
        Self
    }

    fn with_doc<R>(
        &self,
        doc: &PdfiumDoc,
        f: impl FnOnce(&pdfium_render::prelude::PdfDocument<'_>) -> SpdfResult<R>,
    ) -> SpdfResult<R> {
        let mutex = pdfium()?;
        let guard = mutex
            .lock()
            .map_err(|_| SpdfError::Pdf("pdfium mutex poisoned".into()))?;
        let password = doc.password.as_deref();
        let pdf = guard
            .load_pdf_from_byte_slice(&doc.bytes, password)
            .map_err(|e| SpdfError::Pdf(format!("load_pdf_from_byte_slice: {e:?}")))?;
        f(&pdf)
    }
}

impl PdfEngine for PdfiumEngine {
    type Doc = PdfiumDoc;

    fn name(&self) -> &'static str {
        "pdfium"
    }

    fn load_bytes(&self, bytes: &[u8], password: Option<&str>) -> SpdfResult<Self::Doc> {
        let mutex = pdfium()?;
        let guard = mutex
            .lock()
            .map_err(|_| SpdfError::Pdf("pdfium mutex poisoned".into()))?;
        let pdf = guard
            .load_pdf_from_byte_slice(bytes, password)
            .map_err(|e| SpdfError::Pdf(format!("load_pdf_from_byte_slice: {e:?}")))?;
        let num_pages = pdf.pages().len() as u32;
        debug!(pages = num_pages, "pdfium: loaded document");
        drop(pdf);
        drop(guard);
        Ok(PdfiumDoc {
            bytes: bytes.to_vec(),
            num_pages,
            password: password.map(str::to_owned),
        })
    }

    fn load_path(&self, path: &Path, password: Option<&str>) -> SpdfResult<Self::Doc> {
        let bytes = std::fs::read(path)?;
        self.load_bytes(&bytes, password)
    }

    fn extract_page(
        &self,
        doc: &Self::Doc,
        page_num: u32,
        options: ExtractOptions,
    ) -> SpdfResult<PageData> {
        self.with_doc(doc, |pdf| {
            let page_idx: u16 = (page_num
                .checked_sub(1)
                .ok_or_else(|| SpdfError::InvalidInput("page numbers are 1-indexed".into()))?)
                as u16;
            let page = pdf
                .pages()
                .get(page_idx.into())
                .map_err(|e| SpdfError::Pdf(format!("page {page_num}: {e:?}")))?;

            let width = page.width().value as f64;
            let height = page.height().value as f64;

            let text_page = page
                .text()
                .map_err(|e| SpdfError::Pdf(format!("page {page_num} text: {e:?}")))?;

            let mut items: Vec<TextItem> = Vec::new();
            for segment in text_page.segments().iter() {
                let rect = segment.bounds();
                let str_content = segment.text();
                if str_content.is_empty() {
                    continue;
                }
                // PDFium gives points with bottom-left origin; flip Y to match
                // liteparse's top-left convention.
                let top = rect.top().value as f64;
                let bottom = rect.bottom().value as f64;
                let left = rect.left().value as f64;
                let right = rect.right().value as f64;
                let y_top = height - top;
                let item_h = top - bottom;
                let item_w = right - left;
                let mut ti =
                    TextItem::new(str_content, left, y_top, item_w.max(0.0), item_h.max(0.0));
                // Prefer the real font size / name from the segment's first
                // visible glyph: the bbox height depends on which glyphs the
                // run contains (x-height vs. ascenders), which makes it a
                // noisy signal for heading detection.
                let (font_size, font_name) = segment_font(&segment);
                ti.font_size = Some(font_size.unwrap_or(item_h).max(1.0));
                ti.font_name = font_name;
                items.push(ti);
            }

            // Rectangle-based segments duplicate overlapping glyphs and keep
            // RTL scripts in visual order; rebuild such pages from glyphs.
            if items.iter().any(|it| crate::rtl::has_rtl(&it.str)) {
                let runs = crate::rtl::build_runs(page_glyphs(&text_page, height));
                if !runs.is_empty() {
                    items = runs
                        .into_iter()
                        .map(|r| {
                            let mut ti = TextItem::new(r.text, r.x, r.y, r.width, r.height);
                            ti.font_size = Some(r.font_size.max(1.0));
                            ti.font_name = r.font_name;
                            ti
                        })
                        .collect();
                }
            }

            // Values typed into interactive form fields live in widget
            // annotations, not the content stream.
            let mut form_items = Vec::new();
            for field in form_widgets(&page, height) {
                form_items.extend(crate::form::field_items(&field, &items));
            }
            items.extend(form_items);

            let images = if options.extract_images {
                extract_images(&page, height)
            } else {
                Vec::new()
            };

            Ok(PageData {
                page_num,
                width,
                height,
                text_items: items,
                images,
            })
        })
    }

    fn render_page_png(&self, doc: &Self::Doc, page_num: u32, dpi: u32) -> SpdfResult<Vec<u8>> {
        self.with_doc(doc, |pdf| {
            let page_idx: u16 = (page_num
                .checked_sub(1)
                .ok_or_else(|| SpdfError::InvalidInput("page numbers are 1-indexed".into()))?)
                as u16;
            let page = pdf
                .pages()
                .get(page_idx.into())
                .map_err(|e| SpdfError::Pdf(format!("page {page_num}: {e:?}")))?;

            // 72 points per inch; convert DPI to a pixel scale.
            let scale = dpi as f32 / 72.0;
            let cfg = PdfRenderConfig::new().scale_page_by_factor(scale);

            let bitmap = page
                .render_with_config(&cfg)
                .map_err(|e| SpdfError::Pdf(format!("render page {page_num}: {e:?}")))?;

            let img = bitmap
                .as_image()
                .map_err(|e| SpdfError::Pdf(format!("bitmap to image: {e:?}")))?;
            let mut buf: Vec<u8> = Vec::new();
            img.write_to(&mut std::io::Cursor::new(&mut buf), image::ImageFormat::Png)
                .map_err(|e| SpdfError::Pdf(format!("encode png: {e}")))?;
            Ok(buf)
        })
    }
}

/// Iterate the page's objects and collect every image object.
///
/// For each image, we capture PDF-space bounds (top-left origin, Y flipped)
/// and attempt to decode the raw pixel buffer to PNG via the `image` crate.
/// Decode failures are non-fatal: the image entry is still emitted with
/// `data = None` so downstream OCR can re-render the region from the page.
fn extract_images(page: &pdfium_render::prelude::PdfPage<'_>, page_height: f64) -> Vec<Image> {
    use pdfium_render::prelude::PdfPageObjectCommon;
    let mut out = Vec::new();
    for object in page.objects().iter() {
        let Some(image_obj) = object.as_image_object() else {
            continue;
        };
        let Ok(bounds) = object.bounds() else {
            continue;
        };
        let left = bounds.left().value as f64;
        let right = bounds.right().value as f64;
        let top = bounds.top().value as f64;
        let bottom = bounds.bottom().value as f64;
        let w = (right - left).max(0.0);
        let h = (top - bottom).max(0.0);
        if w <= 0.0 || h <= 0.0 {
            continue;
        }

        let png_bytes = encode_image_object_to_png(image_obj);

        out.push(Image {
            x: left,
            y: page_height - top,
            width: w,
            height: h,
            data: png_bytes,
            scale_factor: None,
            original_orientation_angle: None,
            image_type: Some("embedded".into()),
        });
    }
    out
}

/// Try to pull the decoded bitmap for an image object and re-encode it as PNG.
/// Returns `None` on any failure.
fn encode_image_object_to_png(
    image_obj: &pdfium_render::prelude::PdfPageImageObject<'_>,
) -> Option<Vec<u8>> {
    // `get_raw_image` returns a DynamicImage if pdfium could decode the stream.
    let dynamic = image_obj.get_raw_image().ok()?;
    let rgba = dynamic.to_rgba8();
    let (w, h) = (rgba.width(), rgba.height());
    if w == 0 || h == 0 {
        return None;
    }
    let mut buf = std::io::Cursor::new(Vec::with_capacity((w * h * 4) as usize));
    use image::ImageEncoder;
    image::codecs::png::PngEncoder::new(&mut buf)
        .write_image(rgba.as_raw(), w, h, image::ExtendedColorType::Rgba8)
        .ok()?;
    Some(buf.into_inner())
}

/// Visible text-like form field widgets (text, combo and list boxes) that
/// carry a value, in top-left coordinates.
fn form_widgets(
    page: &pdfium_render::prelude::PdfPage<'_>,
    page_height: f64,
) -> Vec<crate::form::FieldWidget> {
    use pdfium_render::prelude::{PdfFormField, PdfPageAnnotationCommon};
    let mut out = Vec::new();
    for annot in page.annotations().iter() {
        let Some(field) = annot.as_form_field() else {
            continue;
        };
        if annot.is_hidden() {
            continue;
        }
        let value = match field {
            PdfFormField::Text(f) if !f.is_password() => f.value(),
            PdfFormField::ComboBox(f) => f.value(),
            PdfFormField::ListBox(f) => f.value(),
            _ => None,
        };
        let Some(value) = value.filter(|v| !v.trim().is_empty()) else {
            continue;
        };
        let Ok(rect) = annot.bounds() else {
            continue;
        };
        let top = rect.top().value as f64;
        let bottom = rect.bottom().value as f64;
        let left = rect.left().value as f64;
        let right = rect.right().value as f64;
        out.push(crate::form::FieldWidget {
            left: left.min(right),
            top: page_height - top.max(bottom),
            width: (right - left).abs(),
            height: (top - bottom).abs(),
            value,
        });
    }
    out
}

/// All non-whitespace, non-generated glyphs of a page in content order,
/// converted to top-left coordinates.
fn page_glyphs(
    text_page: &pdfium_render::prelude::PdfPageText<'_>,
    page_height: f64,
) -> Vec<crate::rtl::Glyph> {
    let mut out = Vec::new();
    for ch in text_page.chars().iter() {
        if ch.is_generated().unwrap_or(false) {
            continue;
        }
        let Some(text) = ch.unicode_string() else {
            continue;
        };
        if text.is_empty() || text.chars().all(|c| c.is_whitespace() || c.is_control()) {
            continue;
        }
        let Ok(rect) = ch.loose_bounds().or_else(|_| ch.tight_bounds()) else {
            continue;
        };
        let size = ch.scaled_font_size().value as f64;
        let top = rect.top().value as f64;
        let bottom = rect.bottom().value as f64;
        let size = if size.is_finite() && size > 0.0 {
            size
        } else {
            (top - bottom).max(1.0)
        };
        let baseline = ch
            .origin_y()
            .map(|y| page_height - y.value as f64)
            .unwrap_or(page_height - bottom);
        let name = ch.font_name();
        out.push(crate::rtl::Glyph {
            text,
            left: rect.left().value as f64,
            right: rect.right().value as f64,
            top: page_height - top,
            bottom: page_height - bottom,
            baseline,
            font_size: size,
            font_name: (!name.is_empty()).then_some(name),
        });
    }
    out
}

/// Font size and name of the first non-whitespace glyph in a text segment.
/// A font whose weight is >= 700 but whose name carries no weight hint gets
/// a `,Bold` suffix (the conventional PDF style suffix) so downstream
/// consumers can detect bold runs from the name alone.
fn segment_font(
    segment: &pdfium_render::prelude::PdfPageTextSegment<'_>,
) -> (Option<f64>, Option<String>) {
    use pdfium_render::prelude::PdfFontWeight;
    let Ok(chars) = segment.chars() else {
        return (None, None);
    };
    for ch in chars.iter() {
        if ch.unicode_char().is_none_or(char::is_whitespace) {
            continue;
        }
        let size = ch.scaled_font_size().value as f64;
        let size = (size.is_finite() && size > 0.0).then_some(size);
        let mut name = ch.font_name();
        let heavy = matches!(
            ch.font_weight(),
            Some(
                PdfFontWeight::Weight700Bold | PdfFontWeight::Weight800 | PdfFontWeight::Weight900
            )
        ) || matches!(ch.font_weight(), Some(PdfFontWeight::Custom(w)) if w >= 700);
        let lower = name.to_ascii_lowercase();
        if heavy
            && !["bold", "black", "heavy", "semibold"]
                .iter()
                .any(|k| lower.contains(k))
        {
            name.push_str(",Bold");
        }
        let name = (!name.is_empty()).then_some(name);
        return (size, name);
    }
    (None, None)
}
