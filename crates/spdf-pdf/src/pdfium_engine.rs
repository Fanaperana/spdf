//! PDFium-backed implementation of [`crate::PdfEngine`].
//!
//! Port target: `liteparse/src/engines/pdf/pdfjs.ts` (text extraction) +
//! `pdfium-renderer.ts` (rasterization). We unify both under PDFium so the
//! Rust build has a single native dependency.
//!
//! ## Library discovery
//!
//! We try, in order:
//! 1. `Pdfium::bind_to_library(path)` where `path` is `$PDFIUM_LIB_PATH` (an
//!    explicit file path).
//! 2. A copy of `libpdfium` that was embedded at build time (via the
//!    `bundled-pdfium` feature) and extracted to the user cache dir on first
//!    run. This is the default path for end-user installs.
//! 3. `Pdfium::bind_to_library(path)` with a path inferred from the `xtask
//!    pdfium-download` layout — `./pdfium/<triple>/lib/libpdfium.{dylib,so}`
//!    or `./pdfium/<triple>/bin/pdfium.dll`.
//! 4. `Pdfium::bind_to_system_library()` for system-wide installs.
//!
//! ## Threading
//!
//! `pdfium-render`'s bindings are not thread-safe by default; the
//! `thread_safe` feature adds an internal mutex. We still serialise calls
//! through the engine to be defensive against library misuse.

use std::path::{Path, PathBuf};
use std::sync::{Mutex, OnceLock};

use pdfium_render::prelude::{PdfPageObjectsCommon, PdfRenderConfig, Pdfium};
use spdf_types::{Image, Ruling, SpdfError, SpdfResult, TextItem};
use tracing::{debug, warn};

use crate::engine::{ExtractOptions, PageData, PdfDocumentHandle, PdfEngine};

// Generated by `build.rs`. Provides:
//   pub const BYTES: &[u8]      — embedded libpdfium for the host target, or
//                                 an empty slice when bundling is disabled.
//   pub const LIB_NAME: &str    — platform filename (e.g. "libpdfium.so").
mod pdfium_bundle {
    include!(concat!(env!("OUT_DIR"), "/pdfium_bundle.rs"));
}

fn candidate_library_paths() -> Vec<PathBuf> {
    let mut out = Vec::new();
    if let Ok(explicit) = std::env::var("PDFIUM_LIB_PATH") {
        out.push(PathBuf::from(explicit));
    }
    // Embedded library, extracted once to a user cache dir.
    if let Some(p) = extract_bundled_library() {
        out.push(p);
    }
    let triple = current_triple();
    let (subdir, name) = if cfg!(target_os = "windows") {
        ("bin", "pdfium.dll")
    } else if cfg!(target_os = "macos") {
        ("lib", "libpdfium.dylib")
    } else {
        ("lib", "libpdfium.so")
    };
    for root in ["pdfium", "../pdfium", "../../pdfium"] {
        out.push(PathBuf::from(root).join(triple).join(subdir).join(name));
    }
    out
}

/// If a libpdfium was embedded at build time, write it to a stable cache
/// directory (keyed by crate version) and return the path. Returns `None`
/// when bundling was disabled or the write fails — callers fall back to the
/// other discovery mechanisms.
fn extract_bundled_library() -> Option<PathBuf> {
    if pdfium_bundle::BYTES.is_empty() || pdfium_bundle::LIB_NAME.is_empty() {
        return None;
    }
    let cache_root = user_cache_dir()?;
    let dir = cache_root
        .join("spdf")
        .join(concat!("pdfium-v", env!("CARGO_PKG_VERSION")));
    let lib_path = dir.join(pdfium_bundle::LIB_NAME);
    if lib_path.is_file() {
        return Some(lib_path);
    }
    if let Err(e) = std::fs::create_dir_all(&dir) {
        warn!(path = %dir.display(), error = %e, "pdfium: cache mkdir failed");
        return None;
    }
    // Write atomically: write to a temp file, then rename.
    let tmp = dir.join(format!("{}.partial", pdfium_bundle::LIB_NAME));
    if let Err(e) = std::fs::write(&tmp, pdfium_bundle::BYTES) {
        warn!(path = %tmp.display(), error = %e, "pdfium: cache write failed");
        return None;
    }
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        let _ = std::fs::set_permissions(&tmp, std::fs::Permissions::from_mode(0o755));
    }
    if let Err(e) = std::fs::rename(&tmp, &lib_path) {
        warn!(path = %lib_path.display(), error = %e, "pdfium: cache rename failed");
        return None;
    }
    debug!(path = %lib_path.display(), bytes = pdfium_bundle::BYTES.len(), "pdfium: extracted bundled library");
    Some(lib_path)
}

fn user_cache_dir() -> Option<PathBuf> {
    #[cfg(target_os = "windows")]
    {
        if let Some(p) = std::env::var_os("LOCALAPPDATA") {
            return Some(PathBuf::from(p));
        }
    }
    #[cfg(target_os = "macos")]
    {
        if let Some(home) = std::env::var_os("HOME") {
            return Some(PathBuf::from(home).join("Library").join("Caches"));
        }
    }
    #[cfg(all(unix, not(target_os = "macos")))]
    {
        if let Some(xdg) = std::env::var_os("XDG_CACHE_HOME") {
            return Some(PathBuf::from(xdg));
        }
        if let Some(home) = std::env::var_os("HOME") {
            return Some(PathBuf::from(home).join(".cache"));
        }
    }
    // Last-resort fallback: OS temp dir (survives for the session at least).
    Some(std::env::temp_dir())
}

fn current_triple() -> &'static str {
    match (std::env::consts::OS, std::env::consts::ARCH) {
        ("macos", "aarch64") => "aarch64-apple-darwin",
        ("macos", "x86_64") => "x86_64-apple-darwin",
        ("linux", "x86_64") => "x86_64-unknown-linux-gnu",
        ("linux", "aarch64") => "aarch64-unknown-linux-gnu",
        ("windows", "x86_64") => "x86_64-pc-windows-msvc",
        _ => "unknown",
    }
}

/// Global PDFium library handle. PDFium's C API keeps internal global state;
/// a single process-wide instance is the safest usage.
fn pdfium() -> SpdfResult<&'static Mutex<Pdfium>> {
    static LIB: OnceLock<Result<Mutex<Pdfium>, String>> = OnceLock::new();
    let entry = LIB.get_or_init(|| {
        for candidate in candidate_library_paths() {
            if candidate.is_file() {
                let path_str = candidate.to_string_lossy().into_owned();
                match Pdfium::bind_to_library(&path_str) {
                    Ok(b) => {
                        debug!(path = %path_str, "pdfium: bound to explicit library");
                        return Ok(Mutex::new(Pdfium::new(b)));
                    }
                    Err(e) => warn!(path = %path_str, error = %e, "pdfium: explicit bind failed"),
                }
            }
        }
        match Pdfium::bind_to_system_library() {
            Ok(b) => {
                debug!("pdfium: bound to system library");
                Ok(Mutex::new(Pdfium::new(b)))
            }
            Err(e) => Err(format!(
                "no pdfium library found. The default build embeds pdfium; if you \
                 disabled `bundled-pdfium` you must provide one via PDFIUM_LIB_PATH, \
                 `cargo run -p xtask -- pdfium-download`, or a system install. last error: {e}"
            )),
        }
    });
    entry
        .as_ref()
        .map_err(|e| SpdfError::Pdf(format!("pdfium unavailable: {e}")))
}

#[derive(Debug)]
pub struct PdfiumDoc {
    /// We keep the PDF bytes alive for the lifetime of the handle because
    /// `PdfDocument` borrows them internally. Simpler than juggling lifetimes
    /// in a trait object.
    bytes: Vec<u8>,
    num_pages: u32,
    password: Option<String>,
    /// CID -> text maps for fonts without `/ToUnicode`, built on first need.
    font_maps: OnceLock<crate::cidfont::FontMaps>,
}

impl PdfDocumentHandle for PdfiumDoc {
    fn num_pages(&self) -> u32 {
        self.num_pages
    }
}

#[derive(Debug, Default)]
pub struct PdfiumEngine;

impl PdfiumEngine {
    pub fn new() -> Self {
        Self
    }

    fn with_doc<R>(
        &self,
        doc: &PdfiumDoc,
        f: impl FnOnce(&pdfium_render::prelude::PdfDocument<'_>) -> SpdfResult<R>,
    ) -> SpdfResult<R> {
        let mutex = pdfium()?;
        let guard = mutex
            .lock()
            .map_err(|_| SpdfError::Pdf("pdfium mutex poisoned".into()))?;
        let password = doc.password.as_deref();
        let pdf = guard
            .load_pdf_from_byte_slice(&doc.bytes, password)
            .map_err(|e| SpdfError::Pdf(format!("load_pdf_from_byte_slice: {e:?}")))?;
        f(&pdf)
    }
}

impl PdfEngine for PdfiumEngine {
    type Doc = PdfiumDoc;

    fn name(&self) -> &'static str {
        "pdfium"
    }

    fn load_bytes(&self, bytes: &[u8], password: Option<&str>) -> SpdfResult<Self::Doc> {
        let mutex = pdfium()?;
        let guard = mutex
            .lock()
            .map_err(|_| SpdfError::Pdf("pdfium mutex poisoned".into()))?;
        let pdf = guard
            .load_pdf_from_byte_slice(bytes, password)
            .map_err(|e| SpdfError::Pdf(format!("load_pdf_from_byte_slice: {e:?}")))?;
        let num_pages = pdf.pages().len() as u32;
        debug!(pages = num_pages, "pdfium: loaded document");
        drop(pdf);
        drop(guard);
        Ok(PdfiumDoc {
            bytes: bytes.to_vec(),
            num_pages,
            password: password.map(str::to_owned),
            font_maps: OnceLock::new(),
        })
    }

    fn load_path(&self, path: &Path, password: Option<&str>) -> SpdfResult<Self::Doc> {
        let bytes = std::fs::read(path)?;
        self.load_bytes(&bytes, password)
    }

    fn extract_page(
        &self,
        doc: &Self::Doc,
        page_num: u32,
        options: ExtractOptions,
    ) -> SpdfResult<PageData> {
        self.with_doc(doc, |pdf| extract_loaded(pdf, doc, page_num, options))
    }

    /// Opens the document once for the whole batch: PDFium calls are
    /// serialised on one global lock anyway, and re-parsing the file's
    /// cross-reference table per page made extraction grow with
    /// `pages x file size` on long documents.
    fn extract_pages(
        &self,
        doc: &Self::Doc,
        page_nums: &[u32],
        options: ExtractOptions,
    ) -> SpdfResult<Vec<PageData>> {
        self.with_doc(doc, |pdf| {
            page_nums
                .iter()
                .map(|&n| extract_loaded(pdf, doc, n, options))
                .collect()
        })
    }

    fn render_page_png(&self, doc: &Self::Doc, page_num: u32, dpi: u32) -> SpdfResult<Vec<u8>> {
        self.with_doc(doc, |pdf| {
            let page_idx: u16 = (page_num
                .checked_sub(1)
                .ok_or_else(|| SpdfError::InvalidInput("page numbers are 1-indexed".into()))?)
                as u16;
            let page = pdf
                .pages()
                .get(page_idx.into())
                .map_err(|e| SpdfError::Pdf(format!("page {page_num}: {e:?}")))?;

            // 72 points per inch; convert DPI to a pixel scale.
            let scale = dpi as f32 / 72.0;
            let cfg = PdfRenderConfig::new().scale_page_by_factor(scale);

            let bitmap = page
                .render_with_config(&cfg)
                .map_err(|e| SpdfError::Pdf(format!("render page {page_num}: {e:?}")))?;

            let img = bitmap
                .as_image()
                .map_err(|e| SpdfError::Pdf(format!("bitmap to image: {e:?}")))?;
            let mut buf: Vec<u8> = Vec::new();
            img.write_to(&mut std::io::Cursor::new(&mut buf), image::ImageFormat::Png)
                .map_err(|e| SpdfError::Pdf(format!("encode png: {e}")))?;
            Ok(buf)
        })
    }

    fn render_page_rgb(
        &self,
        doc: &Self::Doc,
        page_num: u32,
        dpi: u32,
    ) -> SpdfResult<crate::engine::RgbPixels> {
        self.with_doc(doc, |pdf| {
            let page_idx: u16 = (page_num
                .checked_sub(1)
                .ok_or_else(|| SpdfError::InvalidInput("page numbers are 1-indexed".into()))?)
                as u16;
            let page = pdf
                .pages()
                .get(page_idx.into())
                .map_err(|e| SpdfError::Pdf(format!("page {page_num}: {e:?}")))?;
            let cfg = PdfRenderConfig::new().scale_page_by_factor(dpi as f32 / 72.0);
            let bitmap = page
                .render_with_config(&cfg)
                .map_err(|e| SpdfError::Pdf(format!("render page {page_num}: {e:?}")))?;
            // No PNG round trip: OCR wants the pixels.
            let (w, h) = (bitmap.width() as usize, bitmap.height() as usize);
            let rgba = bitmap.as_rgba_bytes();
            drop(bitmap);
            if rgba.len() < w * h * 4 {
                return Err(SpdfError::Pdf(format!(
                    "render page {page_num}: unexpected bitmap layout"
                )));
            }
            Ok(crate::engine::RgbPixels::from_rgba(w, h, &rgba))
        })
    }
}

/// Extract one page from an already opened document.
fn extract_loaded(
    pdf: &pdfium_render::prelude::PdfDocument<'_>,
    doc: &PdfiumDoc,
    page_num: u32,
    options: ExtractOptions,
) -> SpdfResult<PageData> {
    let page_idx: u16 = (page_num
        .checked_sub(1)
        .ok_or_else(|| SpdfError::InvalidInput("page numbers are 1-indexed".into()))?)
        as u16;
    let page = pdf
        .pages()
        .get(page_idx.into())
        .map_err(|e| SpdfError::Pdf(format!("page {page_num}: {e:?}")))?;

    let width = page.width().value as f64;
    let height = page.height().value as f64;
    // Positions come in user space; map them into the visible box.
    let frame = page
        .boundaries()
        .bounding()
        .ok()
        .and_then(|b| {
            let r = b.bounds;
            crate::frame::PageFrame::new(
                r.left().value as f64,
                r.bottom().value as f64,
                r.right().value as f64,
                r.top().value as f64,
            )
        })
        .unwrap_or_else(|| crate::frame::PageFrame::origin(width, height));

    let text_page = page
        .text()
        .map_err(|e| SpdfError::Pdf(format!("page {page_num} text: {e:?}")))?;

    let mut items: Vec<TextItem> = Vec::new();
    let all_segments = text_page.segments();
    let segments: Vec<_> = all_segments.iter().collect();
    // Exact per-segment text from the page's characters; PDFium's
    // rectangle query re-reads overlapping neighbours' glyphs.
    let exact = segment_texts(&text_page, &segments);
    for (si, segment) in segments.iter().enumerate() {
        let rect = segment.bounds();
        let seg_exact = exact.as_ref().map(|e| &e[si]);
        let str_content = match seg_exact {
            Some(e) => e.text.clone(),
            None => segment.text(),
        };
        if str_content.is_empty() {
            continue;
        }
        // PDFium gives points with bottom-left origin; flip Y to match
        // liteparse's top-left convention.
        let top = rect.top().value as f64;
        let bottom = rect.bottom().value as f64;
        let left = rect.left().value as f64;
        let right = rect.right().value as f64;
        let y_top = frame.y(top);
        let item_h = top - bottom;
        let item_w = right - left;
        let mut ti = TextItem::new(str_content, left, y_top, item_w.max(0.0), item_h.max(0.0));
        // Prefer the real font size / name from the segment's first
        // visible glyph: the bbox height depends on which glyphs the
        // run contains (x-height vs. ascenders), which makes it a
        // noisy signal for heading detection.
        let (font_size, font_name) = segment_font(segment);
        let size = font_size.unwrap_or(item_h).max(1.0);
        ti.font_size = Some(size);
        ti.font_name = font_name;
        // Table rows drawn as one run come back as one segment;
        // cut it at column gutters so cells stay apart.
        if crate::gutter::suspicious(&ti.str, item_w, size) {
            let pieces = match seg_exact {
                Some(e) => crate::gutter::split(&ti.str, &e.glyphs, size),
                None => segment_gutters(segment, &ti.str, size),
            };
            if let Some(pieces) = pieces {
                for p in pieces {
                    let mut part =
                        TextItem::new(p.text, p.left, y_top, p.right - p.left, ti.height);
                    part.font_size = ti.font_size;
                    part.font_name = ti.font_name.clone();
                    items.push(part);
                }
                continue;
            }
        }
        items.push(ti);
    }

    // Composite fonts without a ToUnicode CMap come out as raw
    // character codes; recover their text from the embedded font.
    let mut rebuild = None;
    if items
        .iter()
        .any(|it| crate::cidfont::looks_like_raw_codes(&it.str))
    {
        let maps = doc
            .font_maps
            .get_or_init(|| crate::cidfont::recover_font_maps(&doc.bytes));
        if !maps.is_empty() {
            rebuild = Some(maps);
        }
    }

    // Rectangle-based segments duplicate overlapping glyphs and keep
    // RTL scripts in visual order; rebuild such pages from glyphs.
    if rebuild.is_some() || items.iter().any(|it| crate::rtl::has_rtl(&it.str)) {
        let runs = crate::rtl::build_runs(page_glyphs(&text_page, &frame, rebuild));
        if !runs.is_empty() {
            items = runs
                .into_iter()
                .map(|r| {
                    let mut ti = TextItem::new(r.text, r.x, r.y, r.width, r.height);
                    ti.font_size = Some(r.font_size.max(1.0));
                    ti.font_name = r.font_name;
                    ti
                })
                .collect();
        }
    } else {
        // Hyphens that end a line come back as PDFium's U+0002 marker.
        for it in &mut items {
            if let Some(s) = crate::segtext::restore_line_end_hyphen(&it.str) {
                it.str = s;
            }
        }
    }

    // Values typed into interactive form fields live in widget
    // annotations, not the content stream.
    let mut form_items = Vec::new();
    for field in form_widgets(&page, &frame) {
        form_items.extend(crate::form::field_items(&field, &items));
    }
    items.extend(form_items);
    frame.shift_items(&mut items);
    // Text drawn entirely outside the visible box (the other half of
    // a spread, bleed-area slugs) is never displayed.
    items.retain(|it| frame.shows(it));

    let images = if options.extract_images {
        let mut images = extract_images(&page, &frame);
        frame.shift_images(&mut images);
        images
    } else {
        Vec::new()
    };

    let rulings = if options.extract_rulings {
        let mut rulings = extract_rulings(&page, &frame);
        frame.shift_rulings(&mut rulings);
        rulings
    } else {
        Vec::new()
    };

    Ok(PageData {
        page_num,
        width,
        height,
        text_items: items,
        images,
        rulings,
    })
}

/// Upper bound on rules collected per page: vector-art pages can hold
/// tens of thousands of strokes that are never table borders.
const MAX_RULINGS: usize = 20_000;
/// Thickest filled shape still read as a drawn rule, in points.
const MAX_RULE_THICKNESS: f64 = 3.0;

/// Collect the axis-aligned straight edges of the page's visible vector
/// paths: stroked lines and shapes, and thin filled rectangles (a common
/// way to draw table rules).
/// Coordinates are flipped to a top-left origin.
fn extract_rulings(
    page: &pdfium_render::prelude::PdfPage<'_>,
    frame: &crate::frame::PageFrame,
) -> Vec<Ruling> {
    use pdfium_render::prelude::{
        PdfPageObjectCommon, PdfPathFillMode, PdfPathSegmentType, PdfPathSegments,
    };
    let mut out = Vec::new();
    for object in page.objects().iter() {
        if out.len() >= MAX_RULINGS {
            break;
        }
        let Some(path) = object.as_path_object() else {
            continue;
        };
        let stroked = path.is_stroked().unwrap_or(false);
        let filled = !matches!(path.fill_mode(), Ok(PdfPathFillMode::None) | Err(_));
        if !stroked && !filled {
            continue;
        }
        // White fills (page backgrounds, knock-outs) draw nothing visible.
        if !stroked
            && let Ok(c) = object.fill_color()
            && (c.alpha() == 0 || (c.red() >= 250 && c.green() >= 250 && c.blue() >= 250))
        {
            continue;
        }
        let Ok(matrix) = path.matrix() else {
            continue;
        };
        let segments = path.segments().transform(matrix);
        let first = out.len();
        let (mut lo_x, mut lo_y, mut hi_x, mut hi_y) = (
            f64::INFINITY,
            f64::INFINITY,
            f64::NEG_INFINITY,
            f64::NEG_INFINITY,
        );
        let mut start: Option<(f64, f64)> = None;
        let mut cur: Option<(f64, f64)> = None;
        for seg in segments.iter() {
            let (x, y) = seg.point();
            let p = (x.value as f64, frame.y(y.value as f64));
            lo_x = lo_x.min(p.0);
            hi_x = hi_x.max(p.0);
            lo_y = lo_y.min(p.1);
            hi_y = hi_y.max(p.1);
            match seg.segment_type() {
                PdfPathSegmentType::MoveTo => {
                    start = Some(p);
                    cur = Some(p);
                    continue;
                }
                PdfPathSegmentType::LineTo => {
                    if let Some(c) = cur {
                        push_ruling(&mut out, c, p);
                    }
                }
                _ => {}
            }
            cur = Some(p);
            if seg.is_close()
                && let Some(s0) = start
            {
                push_ruling(&mut out, p, s0);
                cur = Some(s0);
            }
        }
        // A fill-only path draws a rule only when it is thin; the edges of
        // large shaded areas (cell backgrounds, panels) are not borders.
        if !stroked && (hi_x - lo_x).min(hi_y - lo_y) > MAX_RULE_THICKNESS {
            out.truncate(first);
        }
    }
    out
}

/// Record the edge `a -> b` when it is (nearly) horizontal or vertical.
fn push_ruling(out: &mut Vec<Ruling>, a: (f64, f64), b: (f64, f64)) {
    const AXIS_TOL: f64 = 0.5;
    const MIN_LEN: f64 = 1.0;
    let (dx, dy) = ((b.0 - a.0).abs(), (b.1 - a.1).abs());
    if !(a.0.is_finite() && a.1.is_finite() && b.0.is_finite() && b.1.is_finite()) {
        return;
    }
    if dy <= AXIS_TOL && dx >= MIN_LEN {
        let y = (a.1 + b.1) / 2.0;
        out.push(Ruling {
            x1: a.0.min(b.0),
            y1: y,
            x2: a.0.max(b.0),
            y2: y,
        });
    } else if dx <= AXIS_TOL && dy >= MIN_LEN {
        let x = (a.0 + b.0) / 2.0;
        out.push(Ruling {
            x1: x,
            y1: a.1.min(b.1),
            x2: x,
            y2: a.1.max(b.1),
        });
    }
}

/// Iterate the page's objects and collect every image object.
///
/// For each image, we capture PDF-space bounds (top-left origin, Y flipped).
/// Pixels are not decoded (`data = None`): OCR re-renders the whole page.
fn extract_images(
    page: &pdfium_render::prelude::PdfPage<'_>,
    frame: &crate::frame::PageFrame,
) -> Vec<Image> {
    use pdfium_render::prelude::PdfPageObjectCommon;
    let mut out = Vec::new();
    for object in page.objects().iter() {
        if object.as_image_object().is_none() {
            continue;
        }
        let Ok(bounds) = object.bounds() else {
            continue;
        };
        let left = bounds.left().value as f64;
        let right = bounds.right().value as f64;
        let top = bounds.top().value as f64;
        let bottom = bounds.bottom().value as f64;
        let w = (right - left).max(0.0);
        let h = (top - bottom).max(0.0);
        if w <= 0.0 || h <= 0.0 {
            continue;
        }

        out.push(Image {
            x: left,
            y: frame.y(top),
            width: w,
            height: h,
            // Only the placement is needed (it decides which pages get
            // OCR, which renders the page itself); decoding and
            // re-encoding every scan bitmap here cost ~40 ms and a full
            // RGBA copy per page.
            data: None,
            scale_factor: None,
            original_orientation_angle: None,
            image_type: Some("embedded".into()),
        });
    }
    out
}

/// Visible text-like form field widgets (text, combo and list boxes) that
/// carry a value, in top-left coordinates.
fn form_widgets(
    page: &pdfium_render::prelude::PdfPage<'_>,
    frame: &crate::frame::PageFrame,
) -> Vec<crate::form::FieldWidget> {
    use pdfium_render::prelude::{PdfFormField, PdfPageAnnotationCommon};
    let mut out = Vec::new();
    for annot in page.annotations().iter() {
        let Some(field) = annot.as_form_field() else {
            continue;
        };
        if annot.is_hidden() {
            continue;
        }
        let value = match field {
            PdfFormField::Text(f) if !f.is_password() => f.value(),
            PdfFormField::ComboBox(f) => f.value(),
            PdfFormField::ListBox(f) => f.value(),
            _ => None,
        };
        let Some(value) = value.filter(|v| !v.trim().is_empty()) else {
            continue;
        };
        let Ok(rect) = annot.bounds() else {
            continue;
        };
        let top = rect.top().value as f64;
        let bottom = rect.bottom().value as f64;
        let left = rect.left().value as f64;
        let right = rect.right().value as f64;
        out.push(crate::form::FieldWidget {
            left: left.min(right),
            top: frame.y(top.max(bottom)),
            width: (right - left).abs(),
            height: (top - bottom).abs(),
            value,
        });
    }
    out
}

/// All non-whitespace, non-generated glyphs of a page in content order,
/// converted to top-left coordinates.
///
/// With `font_maps`, characters drawn in a font that has a recovered CID map
/// take their text from it (PDFium reports such characters as raw codes).
fn page_glyphs(
    text_page: &pdfium_render::prelude::PdfPageText<'_>,
    frame: &crate::frame::PageFrame,
    font_maps: Option<&crate::cidfont::FontMaps>,
) -> Vec<crate::rtl::Glyph> {
    let mut out = Vec::new();
    let mut font_known: std::collections::HashMap<String, bool> = Default::default();
    for ch in text_page.chars().iter() {
        if ch.is_generated().unwrap_or(false) {
            continue;
        }
        let Some(mut text) = ch.unicode_string() else {
            continue;
        };
        if let Some(maps) = font_maps {
            let name = ch.font_name();
            let known = *font_known
                .entry(name.clone())
                .or_insert_with(|| maps.has_font(&name));
            if known {
                let mut cs = text.chars();
                if let (Some(c), None) = (cs.next(), cs.next())
                    && let Some(mapped) = maps.lookup(&name, c as u32)
                {
                    text = mapped.to_string();
                }
            }
        }
        if text.is_empty() || text.chars().all(|c| c.is_whitespace() || c.is_control()) {
            continue;
        }
        let Ok(rect) = ch.loose_bounds().or_else(|_| ch.tight_bounds()) else {
            continue;
        };
        let size = ch.scaled_font_size().value as f64;
        let top = rect.top().value as f64;
        let bottom = rect.bottom().value as f64;
        let size = if size.is_finite() && size > 0.0 {
            size
        } else {
            (top - bottom).max(1.0)
        };
        let baseline = ch
            .origin_y()
            .map(|y| frame.y(y.value as f64))
            .unwrap_or(frame.y(bottom));
        let name = ch.font_name();
        out.push(crate::rtl::Glyph {
            text,
            left: rect.left().value as f64,
            right: rect.right().value as f64,
            top: frame.y(top),
            bottom: frame.y(bottom),
            baseline,
            font_size: size,
            font_name: (!name.is_empty()).then_some(name),
        });
    }
    out
}

/// Re-derive every segment's text from the page's characters (see
/// [`crate::segtext`]). `None` keeps PDFium's rectangle-based text.
fn segment_texts(
    text_page: &pdfium_render::prelude::PdfPageText<'_>,
    segments: &[pdfium_render::prelude::PdfPageTextSegment<'_>],
) -> Option<Vec<crate::segtext::SegText>> {
    use crate::segtext::{PageChar, Rect};
    if segments.is_empty() {
        return None;
    }
    let to_rect = |r: pdfium_render::prelude::PdfRect| Rect {
        left: r.left().value as f64,
        bottom: r.bottom().value as f64,
        right: r.right().value as f64,
        top: r.top().value as f64,
    };
    let rects: Vec<Rect> = segments.iter().map(|s| to_rect(s.bounds())).collect();
    let chars = text_page.chars();
    let mut page_chars = Vec::with_capacity(chars.len());
    for ch in chars.iter() {
        let Some(text) = ch.unicode_string() else {
            continue;
        };
        let generated = ch.is_generated().unwrap_or(false);
        let (rect, extent) = if generated {
            (None, None)
        } else {
            let extent = ch
                .loose_bounds()
                .ok()
                .map(|r| (r.left().value as f64, r.right().value as f64));
            (ch.tight_bounds().ok().map(to_rect), extent)
        };
        page_chars.push(PageChar {
            text,
            generated,
            rect,
            extent,
        });
    }
    crate::segtext::assign(&page_chars, &rects)
}

/// Split a segment at column gutters using its glyphs' horizontal extents.
fn segment_gutters(
    segment: &pdfium_render::prelude::PdfPageTextSegment<'_>,
    text: &str,
    font_size: f64,
) -> Option<Vec<crate::gutter::Piece>> {
    let bounds = segment.bounds();
    let (top, bottom) = (bounds.top().value, bounds.bottom().value);
    let (left, right) = (bounds.left().value, bounds.right().value);
    let chars = segment.chars().ok()?;
    let mut glyphs = Vec::new();
    for ch in chars.iter() {
        if ch.is_generated().unwrap_or(false) {
            continue;
        }
        let Some(c) = ch.unicode_char() else {
            continue;
        };
        if c.is_whitespace() || c.is_control() {
            continue;
        }
        let rect = ch.loose_bounds().or_else(|_| ch.tight_bounds()).ok()?;
        // `chars()` is a fuzzy index range; keep glyphs inside the segment.
        let cx = (rect.left().value + rect.right().value) / 2.0;
        let cy = (rect.top().value + rect.bottom().value) / 2.0;
        if cx < left - 0.5 || cx > right + 0.5 || cy < bottom - 0.5 || cy > top + 0.5 {
            continue;
        }
        glyphs.push((rect.left().value as f64, rect.right().value as f64));
    }
    crate::gutter::split(text, &glyphs, font_size)
}

/// Font size and name of the first non-whitespace glyph in a text segment.
/// A font whose weight is >= 700 but whose name carries no weight hint gets
/// a `,Bold` suffix (the conventional PDF style suffix) so downstream
/// consumers can detect bold runs from the name alone.
fn segment_font(
    segment: &pdfium_render::prelude::PdfPageTextSegment<'_>,
) -> (Option<f64>, Option<String>) {
    use pdfium_render::prelude::PdfFontWeight;
    let Ok(chars) = segment.chars() else {
        return (None, None);
    };
    for ch in chars.iter() {
        if ch.unicode_char().is_none_or(char::is_whitespace) {
            continue;
        }
        let size = ch.scaled_font_size().value as f64;
        let size = (size.is_finite() && size > 0.0).then_some(size);
        let mut name = ch.font_name();
        let heavy = matches!(
            ch.font_weight(),
            Some(
                PdfFontWeight::Weight700Bold | PdfFontWeight::Weight800 | PdfFontWeight::Weight900
            )
        ) || matches!(ch.font_weight(), Some(PdfFontWeight::Custom(w)) if w >= 700);
        let lower = name.to_ascii_lowercase();
        if heavy
            && !["bold", "black", "heavy", "semibold"]
                .iter()
                .any(|k| lower.contains(k))
        {
            name.push_str(",Bold");
        }
        let name = (!name.is_empty()).then_some(name);
        return (size, name);
    }
    (None, None)
}
